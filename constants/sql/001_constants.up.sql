-- Apply once through the application's migration runner, before project seeds.
-- Notifications contain identities only and are delivered on transaction commit.
CREATE TABLE public.webapp_constants (
	id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	code text NOT NULL UNIQUE CHECK (code <> '' AND code = btrim(code) AND octet_length(code) <= 256),
	name text NOT NULL,
	description text NOT NULL DEFAULT '',
	value_type text NOT NULL CHECK (value_type IN ('bool', 'int64', 'float64', 'string', 'decimal', 'json')),
	value jsonb NOT NULL,
	version bigint NOT NULL DEFAULT 1 CHECK (version > 0),
	updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
	CONSTRAINT webapp_constants_value_kind CHECK (
		value = 'null'::jsonb OR
		CASE value_type
			WHEN 'bool' THEN jsonb_typeof(value) = 'boolean'
			WHEN 'string' THEN jsonb_typeof(value) = 'string'
			WHEN 'decimal' THEN jsonb_typeof(value) = 'string'
				AND (value #>> '{}') ~ '^-?(0|[1-9][0-9]*)(\.[0-9]+)?$'
			WHEN 'int64' THEN CASE WHEN jsonb_typeof(value) = 'number' THEN
				(value::text) ~ '^-?(0|[1-9][0-9]*)$'
				AND (value::text)::numeric = trunc((value::text)::numeric)
				AND (value::text)::numeric BETWEEN -9223372036854775808 AND 9223372036854775807
				ELSE false END
			WHEN 'float64' THEN CASE WHEN jsonb_typeof(value) = 'number' THEN
				abs((value::text)::numeric) <= 1.7976931348623157e308::numeric
				ELSE false END
			WHEN 'json' THEN true
			ELSE false
		END
	)
);

CREATE FUNCTION public.webapp_constants_before_write()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
BEGIN
	IF TG_OP = 'INSERT' THEN
		NEW.version := 1;
		NEW.updated_at := clock_timestamp();
		RETURN NEW;
	END IF;
	IF NEW.id IS DISTINCT FROM OLD.id OR NEW.code IS DISTINCT FROM OLD.code THEN
		RAISE EXCEPTION 'constant IDs and codes are immutable' USING ERRCODE = '23514';
	END IF;
	IF ROW(NEW.name, NEW.description, NEW.value_type, NEW.value)
		IS DISTINCT FROM ROW(OLD.name, OLD.description, OLD.value_type, OLD.value) THEN
		NEW.version := OLD.version + 1;
		NEW.updated_at := clock_timestamp();
	ELSE
		NEW.version := OLD.version;
		NEW.updated_at := OLD.updated_at;
	END IF;
	RETURN NEW;
END;
$$;

CREATE FUNCTION public.webapp_constants_notify()
RETURNS trigger
LANGUAGE plpgsql
SET search_path = pg_catalog, public
AS $$
DECLARE
	payload text;
BEGIN
	IF TG_OP = 'TRUNCATE' THEN
		PERFORM pg_notify('webapp_constants_changed', '{"reset":true}');
		RETURN NULL;
	ELSIF TG_OP = 'DELETE' THEN
		payload := json_build_object('id', OLD.id, 'code', OLD.code,
			'version', OLD.version + 1, 'operation', TG_OP)::text;
	ELSIF TG_OP = 'UPDATE' AND NEW.version = OLD.version THEN
		RETURN NULL;
	ELSE
		payload := json_build_object('id', NEW.id, 'code', NEW.code,
			'version', NEW.version, 'operation', TG_OP)::text;
	END IF;
	PERFORM pg_notify('webapp_constants_changed', payload);
	RETURN NULL;
END;
$$;

CREATE TRIGGER webapp_constants_before_write
	BEFORE INSERT OR UPDATE ON public.webapp_constants
	FOR EACH ROW EXECUTE FUNCTION public.webapp_constants_before_write();

CREATE TRIGGER webapp_constants_notify
	AFTER INSERT OR UPDATE OR DELETE ON public.webapp_constants
	FOR EACH ROW EXECUTE FUNCTION public.webapp_constants_notify();

CREATE TRIGGER webapp_constants_notify_truncate
	AFTER TRUNCATE ON public.webapp_constants
	FOR EACH STATEMENT EXECUTE FUNCTION public.webapp_constants_notify();
